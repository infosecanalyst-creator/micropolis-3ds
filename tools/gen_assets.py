#!/usr/bin/env python3
"""Convert Micropolis graphics into C headers for the 3DS frontend.

Usage: gen_assets.py <MicropolisCore/src/images/micropolisEngine dir> <out dir>

Produces:
  tiles_data.h    960 tiles x 16x16, 8-bit palette indices + shared palette
  sprites_data.h  8 sprite types, per-frame indexed bitmaps, index 255 = clear
  icons_data.h    tool-bar icons (56x24), indexed, 255 = clear
All images share ONE 256-colour palette so the renderer needs a single LUT.
"""
import os
import sys
from PIL import Image

src = sys.argv[1]
out = sys.argv[2]
TRANSPARENT = 255

# ---- gather every image so one palette covers all of them ---------------
tiles = Image.open(os.path.join(src, "tiles.png")).convert("RGBA")
assert tiles.size == (256, 960), tiles.size

SPRITE_FRAMES = {1: 5, 2: 8, 3: 11, 4: 8, 5: 16, 6: 3, 7: 6, 8: 4}
sprites = {}
for t, n in SPRITE_FRAMES.items():
    frames = []
    for i in range(n):
        p = os.path.join(src, "obj%d-%d.png" % (t, i))
        frames.append(Image.open(p).convert("RGBA"))
    sprites[t] = frames

ICONS = ["res", "com", "ind", "fire", "pol", "qry", "wire", "dozr", "rail",
         "road", "stad", "park", "seap", "coal", "nuc", "airp", "chlk", "ersr"]
icons = {}
for name in ICONS:
    p = os.path.join(src, "ic%s.png" % name)
    if not os.path.exists(p):
        continue
    im = Image.open(p)
    if im.mode == "I;16":
        import numpy as np
        arr = (np.array(im, dtype="uint32") // 256).astype("uint8")
        im = Image.fromarray(arr, "L").convert("RGBA")
    icons[name] = im.convert("RGBA")

# Build the palette from all opaque pixels (quantize to 255 colours).
strip = Image.new("RGB", (256, 960 + 48 * 70 + 24 * 20), (0, 0, 0))
strip.paste(tiles.convert("RGB"), (0, 0))
y = 960
for t, frames in sprites.items():
    for f in frames:
        bg = Image.new("RGB", f.size, (255, 0, 255))
        bg.paste(f, (0, 0), f)
        strip.paste(bg, (0, y))
        y += f.size[1]
for name, im in icons.items():
    strip.paste(im.convert("RGB"), (0, y))
    y += im.size[1]
strip = strip.crop((0, 0, 256, y))
quant = strip.quantize(colors=255, method=Image.MEDIANCUT, dither=Image.NONE)
pal = quant.getpalette()[:255 * 3]
palette = [tuple(pal[i:i + 3]) for i in range(0, len(pal), 3)]
palette.append((255, 0, 255))  # index 255 = transparent marker


def nearest(rgb):
    r, g, b = rgb
    best, bi = 1 << 30, 0
    for i, (pr, pg, pb) in enumerate(palette[:255]):
        d = (r - pr) ** 2 + (g - pg) ** 2 + (b - pb) ** 2
        if d < best:
            best, bi = d, i
    return bi


cache = {}


def idx(px):
    r, g, b, a = px
    if a < 128:
        return TRANSPARENT
    k = (r, g, b)
    if k not in cache:
        cache[k] = nearest(k)
    return cache[k]


def indexed(im):
    w, h = im.size
    data = im.load()
    return [idx(data[x, y]) for y in range(h) for x in range(w)]


def emit_array(f, name, data, per_line=32):
    f.write("static const unsigned char %s[%d] = {\n" % (name, len(data)))
    for i in range(0, len(data), per_line):
        f.write(",".join(str(v) for v in data[i:i + per_line]) + ",\n")
    f.write("};\n\n")


os.makedirs(out, exist_ok=True)

# ---- palette + tiles ------------------------------------------------------
with open(os.path.join(out, "tiles_data.h"), "w") as f:
    f.write("// Generated by tools/gen_assets.py -- do not edit.\n#pragma once\n\n")
    f.write("#define TILE_SIZE 16\n#define TILE_COUNT 960\n#define PAL_TRANSPARENT 255\n\n")
    f.write("static const unsigned char mp_palette[256][3] = {\n")
    for r, g, b in palette:
        f.write("{%d,%d,%d}," % (r, g, b))
    f.write("\n};\n\n")
    tdata = []
    for t in range(960):
        tx, ty = (t % 16) * 16, (t // 16) * 16
        tdata.extend(indexed(tiles.crop((tx, ty, tx + 16, ty + 16))))
    # tiles are opaque; map stray transparents to black-ish index
    tdata = [v if v != TRANSPARENT else 0 for v in tdata]
    f.write("// tile t occupies mp_tiles[t*256 .. t*256+255], row-major 16x16\n")
    emit_array(f, "mp_tiles", tdata)
print("tiles ok")

# ---- sprites --------------------------------------------------------------
with open(os.path.join(out, "sprites_data.h"), "w") as f:
    f.write("// Generated by tools/gen_assets.py -- do not edit.\n#pragma once\n\n")
    f.write("struct SpriteFrame { unsigned short w, h; const unsigned char *px; };\n\n")
    for t, frames in sprites.items():
        for i, fr in enumerate(frames):
            emit_array(f, "mp_spr%d_%d" % (t, i), indexed(fr))
    f.write("static const SpriteFrame mp_sprite_frames[9][16] = {\n  {{0,0,0}},\n")
    for t in range(1, 9):
        frames = sprites[t]
        f.write("  {")
        for i in range(16):
            if i < len(frames):
                f.write("{%d,%d,mp_spr%d_%d}," % (frames[i].size[0], frames[i].size[1], t, i))
            else:
                f.write("{0,0,0},")
        f.write("},\n")
    f.write("};\n")
    f.write("static const unsigned char mp_sprite_nframes[9] = {0,%s};\n" %
            ",".join(str(SPRITE_FRAMES[t]) for t in range(1, 9)))
print("sprites ok")

# ---- icons ----------------------------------------------------------------
with open(os.path.join(out, "icons_data.h"), "w") as f:
    f.write("// Generated by tools/gen_assets.py -- do not edit.\n#pragma once\n\n")
    f.write("#define ICON_W 56\n#define ICON_H 24\n\n")
    names = []
    for name, im in icons.items():
        if im.size != (56, 24):
            im = im.resize((56, 24))
        emit_array(f, "mp_icon_%s" % name, indexed(im))
        names.append(name)
    f.write("static const unsigned char *const mp_icons[] = {%s};\n" %
            ",".join("mp_icon_%s" % n for n in names))
    f.write("static const char *const mp_icon_names[] = {%s};\n" %
            ",".join('"%s"' % n for n in names))
    f.write("#define ICON_COUNT %d\n" % len(names))
print("icons ok:", names)
