#!/usr/bin/env python3
"""Crisp bitmap font header from a TTF using FreeType's hinted 1-bit raster
(no downsampling). Usage: gen_font2.py <ttf> <out.h> <cellW> <cellH> <ptsize> [NAME]"""
import sys
from PIL import Image, ImageFont, ImageDraw
ttf, out, W, H, PT = sys.argv[1], sys.argv[2], int(sys.argv[3]), int(sys.argv[4]), int(sys.argv[5])
NAME = sys.argv[6] if len(sys.argv) > 6 else "font"
font = ImageFont.truetype(ttf, PT)
asc, desc = font.getmetrics()
cps = list(range(0x20, 0x7F)) + list(range(0xA0, 0x100)) + [0x2500, 0x2502, 0x2588, 0x2591, 0x2592, 0x2593, 0x25BA, 0x25C4, 0x2191, 0x2193, 0x2190, 0x2192]
glyphs = []  # sorted by codepoint below (binary search in fb.h)
for cp in cps:
    im = Image.new("1", (W, H), 0)
    d = ImageDraw.Draw(im)
    ch = chr(cp)
    try:
        bb = font.getbbox(ch)
    except Exception:
        continue
    adv = font.getlength(ch)
    x = int(round((W - adv) / 2))
    # baseline so that ascender fits: top padding = H - (asc+desc) if positive
    y = max(0, (H - (asc + desc)) // 2)
    d.text((x, y), ch, fill=1, font=font)
    px = im.load()
    rows = [sum((1 << (W - 1 - xx)) for xx in range(W) if px[xx, yy]) for yy in range(H)]
    if cp != 0x20 and not any(rows):
        continue
    glyphs.append((cp, rows))
glyphs.sort(key=lambda g: g[0])
N = NAME.upper()
with open(out, "w") as f:
    f.write("// Generated by tools/gen_font2.py -- do not edit.\n#pragma once\n#include <stdint.h>\n\n")
    f.write("#define %s_W %d\n#define %s_H %d\n#define %s_NGLYPHS %d\n\n" % (N, W, N, H, N, len(glyphs)))
    f.write("static const uint32_t %s_cp[%s_NGLYPHS] = {\n" % (NAME, N))
    f.write(",".join("0x%04X" % cp for cp, _ in glyphs) + "\n};\n\n")
    f.write("static const uint16_t %s_bits[%s_NGLYPHS][%s_H] = {\n" % (NAME, N, N))
    for cp, rows in glyphs:
        f.write("{" + ",".join("0x%03X" % r for r in rows) + "}, // U+%04X\n" % cp)
    f.write("};\n")
# preview
cols = 32; rows_n = (len(glyphs) + cols - 1) // cols
img = Image.new("L", (cols * (W + 1), rows_n * (H + 1)), 0)
pxo = img.load()
for i, (cp, rows) in enumerate(glyphs):
    gx, gy = (i % cols) * (W + 1), (i // cols) * (H + 1)
    for yy, r in enumerate(rows):
        for xx in range(W):
            if r & (1 << (W - 1 - xx)): pxo[gx + xx, gy + yy] = 255
img.resize((img.size[0] * 3, img.size[1] * 3), Image.NEAREST).save(out + ".png")
print("wrote", out, len(glyphs), "glyphs")
