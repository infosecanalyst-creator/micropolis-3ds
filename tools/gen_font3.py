#!/usr/bin/env python3
"""Hand-drawn X11 misc-fixed bitmap font (PCF) -> font header used by src/fb.h.
Usage: gen_font3.py <font.pcf> <out.h> <cellW> <cellH> <NAME>
ASCII comes from the PCF; the two UI arrows (U+25C4/U+25BA) are drawn here."""
import sys, os, tempfile
from PIL import PcfFontFile, ImageFont, Image, ImageDraw
pcf, out, W, H, NAME = sys.argv[1], sys.argv[2], int(sys.argv[3]), int(sys.argv[4]), sys.argv[5]
tmp = tempfile.mkdtemp()
with open(pcf, "rb") as fp:
    PcfFontFile.PcfFontFile(fp).save(os.path.join(tmp, "f"))
font = ImageFont.load(os.path.join(tmp, "f.pil"))
glyphs = []
def rows_of(im):
    px = im.load()
    return [sum((1 << (W - 1 - x)) for x in range(W) if px[x, y]) for y in range(H)]
for cp in range(0x20, 0x7F):
    im = Image.new("1", (W, H), 0)
    ImageDraw.Draw(im).text((0, 0), chr(cp), font=font, fill=1)
    glyphs.append((cp, rows_of(im)))
# arrows: solid triangles, vertically centred on the x-height
for cp, left in ((0x25BA, False), (0x25C4, True)):
    im = Image.new("1", (W, H), 0); d = ImageDraw.Draw(im)
    cy, hh = H // 2, min(4, W // 2 + 1)
    pts = [(W - 2, cy), (1, cy - hh), (1, cy + hh)] if not left else [(1, cy), (W - 2, cy - hh), (W - 2, cy + hh)]
    d.polygon(pts, fill=1)
    glyphs.append((cp, rows_of(im)))
glyphs.sort(key=lambda g: g[0])
N = NAME.upper()
with open(out, "w") as f:
    f.write("// Generated by tools/gen_font3.py from X11 misc-fixed (public domain) -- do not edit.\n#pragma once\n#include <stdint.h>\n\n")
    f.write("#define %s_W %d\n#define %s_H %d\n#define %s_NGLYPHS %d\n\n" % (N, W, N, H, N, len(glyphs)))
    f.write("static const uint32_t %s_cp[%s_NGLYPHS] = {\n%s\n};\n\n" % (NAME, N, ",".join("0x%04X" % c for c, _ in glyphs)))
    f.write("static const uint16_t %s_bits[%s_NGLYPHS][%s_H] = {\n" % (NAME, N, N))
    for c, rows in glyphs:
        f.write("{" + ",".join("0x%03X" % r for r in rows) + "}, // U+%04X\n" % c)
    f.write("};\n")
print("wrote", out, len(glyphs), "glyphs")
